text = input("Введіть речення: ")
words = text.split()
longest = max(words, key=len)
shortest = min(words, key=len)
print("Найдовше слово:", longest)
print("Найкоротше слово:", shortest)
unique_words = set(word.lower() for word in words)
unique_count = len(unique_words)
print("Кількість унікальних слів:", unique_count)
replace_word = input("Введіть слово, яке хочете замінити: ")
new_word = input("Введіть слово, яке хочете вставити: ")
new_text = text.replace(replace_word, new_word)
print("Змінене речення:", new_text)
